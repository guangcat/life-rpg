const mime={'.html':'text/html; charset=utf-8','.css':'text/css; charset=utf-8','.mjs':'text/javascript; charset=utf-8','.js':'text/javascript; charset=utf-8','.webmanifest':'application/manifest+json','.png':'image/png'};
const server=http.createServer((req,res)=>{
  let file=decodeURIComponent(new URL(req.url,'http://localhost').pathname).replace(/^\/life-rpg\//,'');
  if(file==='')file='index.html';
  if(!allowed.has(file)){res.writeHead(404);res.end();return;}
  let content=fs.readFileSync(path.join(root,file));
  if(file==='index.html')content=content.toString().replace('<html ','<html data-smoke-version="'+servedVersion+'" ');
  if(file==='sw.js')content=content.toString().replace(/const CACHE = '[^']+';/,"const CACHE = 'liferpg-smoke-"+servedVersion+"';");
  res.writeHead(200,{'Content-Type':mime[path.extname(file)]||'text/plain','Cache-Control':'no-cache'});res.end(content);
});
